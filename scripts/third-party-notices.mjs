#!/usr/bin/env node
/**
 * Writes THIRD_PARTY_NOTICES.md: the npm packages actually bundled into the
 * web app (recorded by the Vite build in apps/web/.build/bundled-packages.json)
 * and into the Cloudflare Worker, with each package's license and the full
 * license and NOTICE texts it ships. Rust crates for the LAN relay are listed
 * in relay/THIRD_PARTY_LICENSES.md.
 *
 *   npm run build && node scripts/third-party-notices.mjs
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { createRequire } from 'node:module';

const root = process.cwd();
const listFile = join(root, 'apps/web/.build/bundled-packages.json');
if (!existsSync(listFile)) {
  console.error('apps/web/.build/bundled-packages.json is missing: run `npm run build` first.');
  process.exit(1);
}

/** @type {Map<string, {name: string, version: string, dir: string}>} */
const packages = new Map();
for (const p of JSON.parse(readFileSync(listFile, 'utf8'))) packages.set(`${p.name}@${p.version}`, { ...p, dir: join(root, p.dir) });

// The Worker bundles the protocol package and its runtime dependencies.
const requireFromWorker = createRequire(join(root, 'packages/protocol/package.json'));
for (const name of Object.keys(JSON.parse(readFileSync(join(root, 'packages/protocol/package.json'), 'utf8')).dependencies ?? {})) {
  let dir = dirname(requireFromWorker.resolve(name));
  while (!existsSync(join(dir, 'package.json')) || JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8')).name !== name) {
    if (dirname(dir) === dir) throw new Error(`could not find the package.json of ${name}`);
    dir = dirname(dir);
  }
  const { version } = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  packages.set(`${name}@${version}`, { name, version, dir });
}

const LICENSE_FILE = /^(licen[cs]e|copying|notice)([.-].*)?$/i;
const rows = [];
const texts = [];
for (const pkg of [...packages.values()].sort((a, b) => a.name.localeCompare(b.name))) {
  const meta = JSON.parse(readFileSync(join(pkg.dir, 'package.json'), 'utf8'));
  const license = typeof meta.license === 'string' ? meta.license : (meta.license?.type ?? 'see license text');
  const rawRepo = typeof meta.repository === 'string' ? meta.repository : (meta.repository?.url ?? '');
  const repo = rawRepo
    .replace(/^git\+/, '')
    .replace(/\.git$/, '')
    .replace(/^git:\/\//, 'https://')
    .replace(/^github:/, 'https://github.com/');
  rows.push(`| ${pkg.name} | ${pkg.version} | ${license} | ${repo} |`);
  for (const f of readdirSync(pkg.dir)
    .filter((f) => LICENSE_FILE.test(f))
    .sort()) {
    const body = readFileSync(join(pkg.dir, f), 'utf8').trim();
    texts.push(`### ${pkg.name} ${pkg.version} (${f})\n\n\`\`\`text\n${body.replace(/```/g, "'''")}\n\`\`\`\n`);
  }
}

writeFileSync(
  join(root, 'THIRD_PARTY_NOTICES.md'),
  [
    '# Third-party notices',
    '',
    'Caption Room is licensed under the GNU AGPL v3 or later (see LICENSE). The web app and Cloudflare Worker builds include the open-source packages below.',
    'Speech models (Moonshine, Whisper, Silero VAD) and the ONNX Runtime WebAssembly files are downloaded at run time and are not part of the build; they are MIT licensed.',
    'Rust crates compiled into the LAN relay are listed in relay/THIRD_PARTY_LICENSES.md.',
    '',
    'Generated by `node scripts/third-party-notices.mjs` after `npm run build`. Do not edit by hand.',
    '',
    '| Package | Version | License | Repository |',
    '| --- | --- | --- | --- |',
    ...rows,
    '',
    '## License and notice texts',
    '',
    ...texts,
  ].join('\n'),
);
console.log(`THIRD_PARTY_NOTICES.md: ${rows.length} packages, ${texts.length} license and notice files`);
